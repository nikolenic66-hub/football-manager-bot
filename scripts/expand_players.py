"""Add missing fictional templates up to TOTAL_PLAYERS without changing existing rows.

New rows fill the target rarity deficits exactly. Existing player names, ratings,
attributes, rarity and club assignments are never updated by this script.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import asyncio
from random import Random
from sqlalchemy import text
from app.db import SessionLocal
from app.seed import TOTAL_PLAYERS, RARITY_COUNTS, _build_seed_rows, _insert_values

INSERT_SQL = text('''
INSERT INTO players(id,first_name,last_name,nationality,age,position,pace,shooting,passing,dribbling,defending,physical,stamina,mental,market_value,salary,potential,rarity,card_version,real_player,preferred_foot,secondary_positions,portrait_url,portrait_source,talents,tactical_archetype,data_source,is_seed,is_template,template_id)
VALUES(:id,:first_name,:last_name,:nationality,:age,:position,:pace,:shooting,:passing,:dribbling,:defending,:physical,:stamina,:mental,:market_value,:salary,:potential,:rarity,:card_version,FALSE,:preferred_foot,:secondary_positions,NULL,NULL,:talents,:tactical_archetype,'seed',TRUE,TRUE,NULL)
''')

async def main():
    rng = Random(20261002)
    rows = _build_seed_rows(rng, TOTAL_PLAYERS)
    async with SessionLocal() as session:
        await session.execute(text("SELECT pg_advisory_xact_lock(hashtext('football-manager-seed'))"))
        all_existing_rows = (await session.execute(text(
            'SELECT id, first_name, last_name, rarity FROM players ORDER BY id'
        ))).mappings().all()
        target_existing_rows = [row for row in all_existing_rows if int(row['id']) <= TOTAL_PLAYERS]
        existing_ids = {int(row['id']) for row in target_existing_rows}
        missing_rows = [row for row in rows if row['id'] not in existing_ids]
        existing_counts = {rarity: 0 for rarity in RARITY_COUNTS}
        for row in target_existing_rows:
            rarity = row['rarity']
            if rarity in existing_counts:
                existing_counts[rarity] += 1
        deficits = {rarity: max(0, target - existing_counts[rarity])
                    for rarity, target in RARITY_COUNTS.items()}
        if sum(deficits.values()) != len(missing_rows):
            raise RuntimeError(
                'Cannot reach target rarity distribution without changing existing players: '
                f'existing={existing_counts}, deficits={deficits}, missing={len(missing_rows)}. '
                'No player rows were inserted.'
            )
        rarity_queue = [rarity for rarity in ('LEGENDARY', 'EPIC', 'RARE', 'BASE')
                        for _ in range(deficits[rarity])]
        used_names = {(str(row['first_name']).casefold(), str(row['last_name']).casefold())
                      for row in all_existing_rows}
        bound_columns = ('id','first_name','last_name','nationality','age','position','pace','shooting','passing','dribbling','defending','physical','stamina','mental','market_value','salary','potential','rarity','card_version','preferred_foot','secondary_positions','talents','tactical_archetype')
        for row, rarity in zip(missing_rows, rarity_queue):
            key = (row['first_name'].casefold(), row['last_name'].casefold())
            if key in used_names:
                # Existing databases may have names generated by an older catalog.
                # Try other deterministic synthetic candidates without touching those rows.
                candidates = [candidate for candidate in rows
                              if (candidate['first_name'].casefold(), candidate['last_name'].casefold()) not in used_names]
                replacement = next((candidate for candidate in candidates if candidate['id'] not in existing_ids), None)
                if replacement is None:
                    raise RuntimeError('No unique fictional names remain for expansion; no transaction committed.')
                row = dict(row, first_name=replacement['first_name'], last_name=replacement['last_name'])
                key = (row['first_name'].casefold(), row['last_name'].casefold())
            used_names.add(key)
            card = 'ICON' if rarity == 'LEGENDARY' else ('EPIC' if rarity == 'EPIC' else 'STANDARD')
            values = _insert_values(row['id'], row['first_name'], row['last_name'],
                                    row['nationality'], row['position'], rarity, rng,
                                    real=False, card=card)
            # Preserve the deterministic name/nationality/position selected above.
            values['age'] = row['age']
            await session.execute(INSERT_SQL, {column: values[column] for column in bound_columns})
        await session.execute(text("SELECT setval('players_id_seq', GREATEST(COALESCE((SELECT MAX(id) FROM players), 1), 1), TRUE)"))
        await session.commit()
    print(f'Added {len(missing_rows)} fictional templates; target IDs: 1..{TOTAL_PLAYERS}.')

if __name__ == '__main__':
    asyncio.run(main())
